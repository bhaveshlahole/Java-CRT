package com.pote.engg.arraydemo;

public class TwoDArray {

	public static void main(String[] args) {
			int [] arr = {10,20,0};
			for(int ele:arr) {
			System.out.println(ele);
	}
			
			
			String [] arys = {"abc","xyz","pqr","opr",null};
			for(String ele:arys) {
			System.out.println(ele);
	}
	}
}
